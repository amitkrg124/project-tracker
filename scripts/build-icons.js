// Copies the Lucide icons the app uses into public/icons.js, so the browser needs no icon library.
// Run with: npm run build:icons
const fs = require('fs');
const path = require('path');

const NAMES = [
  'alarm-clock', 'arrow-down-wide-narrow', 'bell', 'bell-off', 'bell-ring', 'calendar-check', 'calendar-days',
  'check', 'check-check', 'chevron-left', 'chevron-right', 'circle-check', 'clock', 'flag', 'folder',
  'folder-kanban', 'inbox', 'lightbulb', 'list-checks', 'log-out', 'monitor', 'moon', 'pencil', 'plus',
  'send', 'smartphone', 'sun', 'trash-2', 'triangle-alert', 'user-plus', 'users', 'x',
];

const dir = path.join(__dirname, '..', 'node_modules', 'lucide-static', 'icons');
const icons = {};
for (const name of NAMES) {
  const svg = fs.readFileSync(path.join(dir, `${name}.svg`), 'utf8');
  icons[name] = svg.match(/<svg[^>]*>([\s\S]*)<\/svg>/)[1].replace(/\s*\n\s*/g, '').trim();
}

const out = `// Generated by scripts/build-icons.js from lucide-static (ISC license). Do not edit by hand.
const ICON_PATHS = ${JSON.stringify(icons, null, 2)};
`;
fs.writeFileSync(path.join(__dirname, '..', 'public', 'icons.js'), out);
console.log(`Wrote ${NAMES.length} icons to public/icons.js`);
